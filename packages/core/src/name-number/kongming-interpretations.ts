export function getKongmingInterpretation(symbol: string) {
  const entry = /^[●○]{5}$/.test(symbol) ? INTERPRETATIONS[symbol] : undefined;
  if (!entry) throw new Error('未找到对应的孔明神卦释义');
  const [quote, imageMeaning, interpretation, condition] = entry;
  const classical = CLASSICAL_IMAGES[symbol];
  return {
    quote,
    imageMeaning,
    interpretation,
    condition,
    classicalImage: classical ? { title: '《尚书·洪范》', ...classical } : null,
  };
}
