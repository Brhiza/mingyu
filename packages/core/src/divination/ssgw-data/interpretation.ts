function resolveCore(sign: RawSsgwSign): string {
  const override = CORE_OVERRIDES[sign.id];
  if (override) return override;
  return (sign.details.此签核心 || sign.details.解签总论 || sign.qianwen.replace(/\n/g, '；'))
    .replace(/\s+/g, ' ')
    .trim();
}

export function enrichSsgwSign(sign: RawSsgwSign): SsgwSign {
  const interpretation = SIGN_DETAILS[sign.id];
  if (!interpretation) throw new Error(`第${sign.id}签缺少逐签解读。`);
  return {
    ...sign,
    details: {
      ...sign.details,
      核心寓意: resolveCore(sign),
      ...interpretation,
    },
  };
}
