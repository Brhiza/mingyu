export function formatInputError(error: unknown): string {
  if (error && typeof error === 'object' && 'issues' in error && Array.isArray(error.issues)) {
    return error.issues
      .map(
        (issue: {
          path?: PropertyKey[];
          message?: string;
          code?: string;
          expected?: string;
          minimum?: number;
          maximum?: number;
          inclusive?: boolean;
        }) => {
          const field = issue.path?.length
            ? issue.path
                .map((part) => (typeof part === 'string' ? (errorFieldLabels[part] ?? part) : String(part)))
                .join(' / ')
            : '资料';
          const typeNames: Record<string, string> = {
            string: '文字',
            number: '数字',
            int: '整数',
            boolean: '选项',
            array: '列表',
            object: '完整资料',
          };
          const message =
            issue.code === 'invalid_type'
              ? `请填写有效的${typeNames[issue.expected ?? ''] ?? '资料'}。`
              : issue.code === 'too_small'
                ? `数值或长度${issue.inclusive === false ? '必须大于' : '不能小于'} ${issue.minimum}。`
                : issue.code === 'too_big'
                  ? `数值或长度${issue.inclusive === false ? '必须小于' : '不能大于'} ${issue.maximum}。`
                  : issue.code === 'invalid_format'
                    ? '格式不正确，请检查输入。'
                    : (issue.message ?? '输入无效');
          return `${field}：${message}`;
        },
      )
      .join('\n');
  }
  if (error instanceof SyntaxError) return '高级参数不是有效的 JSON，请先检查格式。';
  return error instanceof Error ? error.message : '计算失败';
}
