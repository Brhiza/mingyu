export function getBaziQiongtongAdvice(
  dayMaster: string,
  monthBranch?: string,
): QiongtongTiaohouEntry | undefined {
  const stem = dayMaster?.trim();
  const branch = monthBranch?.trim();
  if (!stem || !branch) return undefined;
  const row = QIONGTONG_RULES[stem]?.[branch];
  if (!row) return undefined;
  return {
    stem,
    monthBranch: branch,
    season: SEASON_DESC[branch] ?? `${branch}月`,
    preferredGods: row[0],
    verse: row[1],
    advice: row[2],
  };
}

export function selectQiongtongExcerpt(
  dayMaster: string,
  monthBranch?: string,
): ClassicExcerpt | undefined {
  const entry = getBaziQiongtongAdvice(dayMaster, monthBranch);
  if (!entry) return undefined;
  return {
    book: '穷通宝鉴',
    chapter: `${entry.stem}日${entry.monthBranch}月`,
    title: `${entry.stem}日生于${entry.monthBranch}月（调候参用 ${entry.preferredGods}）`,
    quote: entry.verse,
    explanation: `${entry.season}：${entry.advice}`,
    condition: `${entry.stem}日主 · ${entry.monthBranch}月令`,
  };
}
