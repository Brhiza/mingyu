export type PromptGuidanceId = keyof typeof PROMPT_GUIDANCE_TEXT;

export type DivinationPromptGuidanceMethod =
  'liuyao' | 'meihua' | 'qimen' | 'liuren' | 'taiyi' | 'tarot' | 'ssgw' | 'almanac' | 'astrolabe';

export type MetaphysicsPromptMethod = 'bazhai' | 'residential' | 'taiyi' | 'qizheng' | 'xuankong';

export function buildPromptGuidanceSections(method: PromptGuidanceId) {
  const guidance = PROMPT_GUIDANCE_TEXT[method];
  const blocks = [
    'tradition' in guidance ? guidance.tradition : '',
    'sources' in guidance ? guidance.sources : '',
  ]
    .filter(Boolean)
    .join('\n\n');

  return blocks ? `【传统依据】\n${blocks}` : '';
}

export function insertPromptSectionBeforeHeading(prompt: string, heading: string, section: string) {
  const normalizedPrompt = prompt.trim();
  const normalizedSection = section.trim();
  if (!normalizedPrompt || !normalizedSection) return normalizedPrompt;

  const marker = `\n\n${heading}`;
  return normalizedPrompt.includes(marker)
    ? normalizedPrompt.replace(marker, `\n\n${normalizedSection}${marker}`)
    : `${normalizedPrompt}\n\n${normalizedSection}`;
}
