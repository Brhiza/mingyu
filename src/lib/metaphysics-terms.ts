const BRANCH_MAP: Record<string, string> = {
  子: '子水',
  丑: '丑土',
  寅: '寅木',
  卯: '卯木',
  辰: '辰土',
  巳: '巳火',
  午: '午火',
  未: '未土',
  申: '申金',
  酉: '酉金',
  戌: '戌土',
  亥: '亥水',
};

export function lookupMetaphysicsTerm(query: string): MetaphysicsTerm | undefined {
  if (!query || typeof query !== 'string') return undefined;

  const raw = query.trim();
  const cleaned = raw.replace(/[[\]【】()（）:：\s]/g, '').replace(/^(伏|身|主|副|见|缺)/, '');

  if (!cleaned) return undefined;

  // 1. 精确干支优先映射 (防止单字 '甲' 或 '子' 误匹配到纳音)
  if (STEM_MAP[cleaned]) {
    const found = METAPHYSICS_TERMS.find((t) => t.term === STEM_MAP[cleaned] || t.term === cleaned);
    if (found) return found;
  }
  if (BRANCH_MAP[cleaned]) {
    const found = METAPHYSICS_TERMS.find(
      (t) => t.term === BRANCH_MAP[cleaned] || t.term === cleaned,
    );
    if (found) return found;
  }

  // 2. 精确术语全匹配 (包括 60 干支 '甲子', '乙丑', 或十神 '正官', 神煞 '德秀贵人')
  const exact = METAPHYSICS_TERMS.find(
    (t) => t.term === cleaned || t.term.toLowerCase() === cleaned.toLowerCase() || t.term === raw,
  );
  if (exact) return exact;

  // 3. 精确别名匹配
  const aliasExact = METAPHYSICS_TERMS.find((t) =>
    t.aliases?.some(
      (a) =>
        a.toLowerCase() === cleaned.toLowerCase() ||
        a === raw ||
        a.toLowerCase() === cleaned.replace(/星$/, '').toLowerCase(),
    ),
  );
  if (aliasExact) return aliasExact;

  // 4. 后缀剥离匹配 ('星', '格', '局', '宫', '爻', '神', '日', '煞', '贵人')
  const stripped = cleaned.replace(/(星|格|局|宫|爻|神|日|煞|贵人)$/, '');
  if (stripped.length >= 2) {
    const strippedMatch = METAPHYSICS_TERMS.find(
      (t) =>
        t.term === stripped || t.term.replace(/(星|格|局|宫|爻|神|日|煞|贵人)$/, '') === stripped,
    );
    if (strippedMatch) return strippedMatch;
  }

  // 5. 包含匹配 (长度 >= 2，避免单字误伤)
  if (cleaned.length >= 2) {
    const substringMatch = METAPHYSICS_TERMS.find(
      (t) =>
        cleaned.includes(t.term) ||
        t.term.includes(cleaned) ||
        t.aliases?.some((a) => a.length >= 2 && (cleaned.includes(a) || a.includes(cleaned))),
    );
    if (substringMatch) return substringMatch;
  }

  return undefined;
}
