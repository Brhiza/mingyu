function angularError(a: number, b: number) {
  return Math.abs(((a - b + 540) % 360) - 180);
}

test('十八张南北半球星盘主星与宫头对照独立星历在一角分内', () => {
  for (const sample of samples) {
    const chart = calculateChart({
      year: sample.year,
      month: 6,
      day: 15,
      hour: 12,
      minute: 0,
      timezone: 0,
      latitude: sample.latitude,
      longitude: sample.longitude,
    });
    const label = `${sample.year}/${sample.latitude}/${sample.longitude}`;
    for (const [index, name] of names.entries()) {
      assert.ok(
        angularError(
          chart.planets.find((p) => p.name === name)!.longitude,
          sample.positions[index],
        ) < tolerance,
        `${label}/${name}`,
      );
    }
    for (const [index, expected] of sample.cusps.entries()) {
      assert.ok(
        angularError(chart.houses.cusps[index].longitude, expected) < tolerance,
        `${label}/第${index + 1}宫`,
      );
    }
    assert.ok(
      angularError(chart.angles.ascendant.longitude, sample.asc) < tolerance,
      `${label}/上升`,
    );
    assert.ok(
      angularError(chart.angles.midheaven.longitude, sample.mc) < tolerance,
      `${label}/天顶`,
    );
  }
});
