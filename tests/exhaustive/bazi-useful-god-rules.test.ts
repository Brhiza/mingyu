import { determineUsefulGod } from '@core/bazi/baziUsefulGodStrategy';

// 用神策略规则全集：仅在穷举层执行。

function runAssertions(
  result: ReturnType<typeof determineUsefulGod>,
  expected: Record<string, unknown>,
) {
  if ('baseFavorableEq' in expected)
    assert.deepEqual(result.decisionEvidence?.base.favorable, expected.baseFavorableEq);
  if ('baseUnfavorableEq' in expected)
    assert.deepEqual(result.decisionEvidence?.base.unfavorable, expected.baseUnfavorableEq);
  if ('climate' in expected) {
    const climate = expected.climate as {
      id: string;
      mode: string;
      status: string;
      adopted: boolean;
      order?: string[];
    };
    const candidate = result.decisionEvidence?.climateCandidates.find(
      (item) => item.ruleId === climate.id,
    );
    assert.ok(candidate, `未找到调候候选：${climate.id}`);
    assert.equal(candidate?.mode, climate.mode);
    assert.equal(candidate?.status, climate.status);
    assert.equal(candidate?.adopted, climate.adopted);
    if (climate.order) assert.deepEqual(candidate?.requestedOrder, climate.order);
  }
  if ('favorableEq' in expected) assert.deepEqual(result.favorableWuxing, expected.favorableEq);
  if ('favorableSlice' in expected) {
    const arr = expected.favorableSlice as unknown[];
    assert.deepEqual(result.favorableWuxing?.slice(0, arr.length), arr);
  }
  if ('favorableFirst' in expected)
    assert.equal(result.favorableWuxing?.[0], expected.favorableFirst);
  if ('favorableAt' in expected) {
    const [idx, val] = expected.favorableAt as [number, string];
    assert.equal(result.favorableWuxing?.[idx], val);
  }
  if ('unfavorableEq' in expected)
    assert.deepEqual(result.unfavorableWuxing, expected.unfavorableEq);
  if ('unfavorableAt' in expected) {
    const [idx, val] = expected.unfavorableAt as [number, string];
    assert.equal(result.unfavorableWuxing?.[idx], val);
  }
  if ('useful' in expected) assert.equal(result.useful, expected.useful);
  if ('avoid' in expected) assert.equal(result.avoid, expected.avoid);
  if ('usefulNot' in expected) assert.notEqual(result.useful, expected.usefulNot);
  if ('avoidNot' in expected) assert.notEqual(result.avoid, expected.avoidNot);
  if ('primaryReason' in expected) assert.equal(result.primaryReason, expected.primaryReason);
  if ('unfavorableNot' in expected) {
    const items = Array.isArray(expected.unfavorableNot)
      ? expected.unfavorableNot
      : [expected.unfavorableNot];
    for (const item of items) assert.ok(!result.unfavorable?.includes(item as string));
  }
  if ('traceMatch' in expected)
    assert.match(result.strategyTrace?.[0] || '', expected.traceMatch as RegExp);
  if ('traceIncludes' in expected) {
    const items = Array.isArray(expected.traceIncludes)
      ? expected.traceIncludes
      : [expected.traceIncludes];
    for (const item of items)
      assert.ok(result.strategyTrace?.some((t) => t.includes(item as string)));
  }
  if ('traceNotIncludes' in expected) {
    const items = Array.isArray(expected.traceNotIncludes)
      ? expected.traceNotIncludes
      : [expected.traceNotIncludes];
    for (const item of items)
      assert.ok(!result.strategyTrace?.some((t) => t.includes(item as string)));
  }
  if ('ruleHas' in expected) {
    const items = Array.isArray(expected.ruleHas) ? expected.ruleHas : [expected.ruleHas];
    for (const item of items) {
      const matched = result.matchedRules?.some((r) => r.id === item);
      const candidate = result.decisionEvidence?.climateCandidates.some(
        (climateCandidate) => climateCandidate.ruleId === item,
      );
      assert.ok(matched || candidate, `未找到规则或调候候选：${item}`);
    }
  }
  if ('ruleNotHas' in expected) {
    const items = Array.isArray(expected.ruleNotHas) ? expected.ruleNotHas : [expected.ruleNotHas];
    for (const item of items) assert.ok(!result.matchedRules?.some((r) => r.id === item));
  }
}

